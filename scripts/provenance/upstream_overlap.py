"""How much of this repo is still upstream's code (honestjams/ac-track-builder).

Upstream has no licence, so files derived from it can't be covered by ours (see LICENSE).
This counts, per file, the meaningful lines (over 12 characters, trimmed) that also appear
anywhere in an upstream checkout, and lists the files that count as upstream-derived.

    git clone https://github.com/honestjams/ac-track-builder /tmp/upstream
    python3 -I scripts/provenance/upstream_overlap.py . /tmp/upstream            # report
    python3 -I scripts/provenance/upstream_overlap.py . /tmp/upstream --write    # also update UPSTREAM-FILES.txt

A file is upstream-derived if at least 20% of its meaningful lines match upstream, or it
shares a path with an upstream file and has 10 or more matching lines. The goal is none.
"""
import collections
import os
import sys

EXTS = (".ts", ".mjs", ".js", ".py", ".lua", ".html", ".css", ".ps1", ".json")
SKIP_DIRS = {".git", "node_modules", "out", "dist", "public"}
SKIP_FILES = {"package-lock.json"}
MIN_LEN = 12


def code_files(root):
    found = {}
    for d, dirs, files in os.walk(root):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
        for f in files:
            if f.endswith(EXTS) and f not in SKIP_FILES:
                p = os.path.join(d, f)
                found[os.path.relpath(p, root).replace(os.sep, "/")] = p
    return found


def lines(path):
    with open(path, errors="ignore") as fh:
        return [s for s in (l.strip() for l in fh) if len(s) > MIN_LEN]


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 2:
        sys.exit(__doc__)
    ours, upstream = args
    up_files = code_files(upstream)
    up_lines = collections.Counter(l for p in up_files.values() for l in lines(p))
    rows, total, matched = [], 0, 0
    for rel, p in sorted(code_files(ours).items()):
        if rel.startswith("scripts/provenance/") or (rel.endswith(".json") and "/" in rel):
            continue  # this script, and data (routes, specs); top-level config files still count
        ls = lines(p)
        m = sum(1 for l in ls if l in up_lines)
        total += len(ls)
        matched += m
        shared = rel in up_files
        derived = (ls and m / len(ls) >= 0.2) or (shared and m >= 10)
        rows.append((rel, m, len(ls), shared, derived))
    derived = [r for r in rows if r[4]]
    print(f"Meaningful lines matching upstream: {matched} of {total} ({matched / max(total, 1):.0%})")
    print(f"Upstream-derived files: {len(derived)} of {len(rows)}")
    for rel, m, n, shared, _ in sorted(derived, key=lambda r: -r[1]):
        print(f"  {m:5}/{n:<5} {m / max(n, 1):4.0%}  {rel}")
    if "--write" in sys.argv:
        out = os.path.join(ours, "UPSTREAM-FILES.txt")
        with open(out, "w") as fh:
            fh.write("# Files derived from honestjams/ac-track-builder (no licence). NOT covered by LICENSE.\n")
            fh.write("# Generated by scripts/provenance/upstream_overlap.py; rewrite a file to take it off this list.\n")
            for rel, *_ in derived:
                fh.write(rel + "\n")
        print(f"Wrote {out}")


if __name__ == "__main__":
    main()
